package docs

// FunctionDoc opis benchmark funkcije
type FunctionDoc struct {
	Name            string  `json:"name"`
	Description     string  `json:"description"`
	Dimensions      string  `json:"dimensions"`
	GlobalMinimum   float64 `json:"global_minimum"`
	GlobalMinimumAt string  `json:"global_minimum_at"`
	// MinPoint je tačna, numerički verifikovana lokacija globalnog minimuma (fn.Evaluate direktno,
	// ne parsiranje GlobalMinimumAt teksta) — za funkcije čiji je pravi minimum van [-5,5] opsega
	// koji /grid renderuje (npr. schwefel, eggholder, alpine_n2), ograničena je na tu domenu jer
	// je namenjena za obeležavanje na renderovanoj 2D/3D površini
	MinPoint         []float64      `json:"min_point"`
	Characteristics  []string       `json:"characteristics"`
	ExamplePoint     []float64      `json:"example_point"`
	ExampleBenchmark map[string]any `json:"example_benchmark"`
}

// SolverDoc opis solver
type SolverDoc struct {
	Name           string         `json:"name"`
	Description    string         `json:"description"`
	Type           string         `json:"type"`
	UsesGradient   bool           `json:"uses_gradient"`
	DefaultPayload map[string]any `json:"default_payload"`
	ExampleRequest map[string]any `json:"example_request"`
}

