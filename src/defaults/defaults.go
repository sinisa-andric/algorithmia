// GetDefaults vraća kopiju default payload-a za method ili generički fallback default ako method nema unos u SolverDefaults
func GetDefaults(method string) map[string]any {
	if defaults, ok := SolverDefaults[method]; ok {
		result := make(map[string]any)
		for k, v := range defaults {
			result[k] = v
		}
		return result
	}
	return map[string]any{
		"max_steps": 1000.0,
		"tolerance": 1e-6,
	}
}

// MergeWithDefaults preklapa payload preko defaulta za method tako da je svaki ključ prisutan u payload-u
func MergeWithDefaults(method string, payload map[string]any) map[string]any {
	merged := GetDefaults(method)
	for k, v := range payload {
		merged[k] = v
	}
	return merged
}
